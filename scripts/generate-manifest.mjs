import { existsSync, writeFileSync } from "node:fs";
import { readIcons, SOURCE_DIR } from "./icons-lib.mjs";

// CI environments (Cloudflare Pages/Workers builds) never have Assets/Images/ —
// it is 258MB of source PNGs and deliberately gitignored. The already-committed
// manifests are the build artifact in that case; only local dev, which has the
// real source tree, needs to regenerate them.
if (!existsSync(SOURCE_DIR)) {
  console.log(`${SOURCE_DIR} not found — using the committed manifests as-is.`);
  process.exit(0);
}

const icons = readIcons();

const clientRows = icons
  .map(
    ({ id, name, category }) =>
      `  { id: ${JSON.stringify(id)}, name: ${JSON.stringify(name)}, category: ${JSON.stringify(
        category
      )}, previewSrc: asset(${JSON.stringify(`${id}.png`)}) },`
  )
  .join("\n");

const BT = String.fromCharCode(96); // backtick — kept out of the template literal below to avoid nesting

const clientManifest = [
  "// Generated by scripts/generate-manifest.mjs — do not edit by hand.",
  "export type Icon = { id: string; name: string; category: string; previewSrc: string };",
  "",
  "// Preview resolution only. Full-resolution keys live server-side (worker/index.ts).",
  "//",
  "// Dev (vite dev): served from Assets/Images/ by the servePreviews plugin in",
  "// vite.config.ts, downscaled on first request — no R2 involved.",
  "// Build (deployed, or wrangler dev): same-origin /preview/<key>, served by the",
  "// Worker straight off the R2 binding (see worker/index.ts). VITE_ASSET_CDN_URL",
  "// is an optional override for routing previews through a dedicated CDN",
  "// subdomain instead, once that's worth the extra DNS and R2 custom-domain setup.",
  "const CDN = import.meta.env.VITE_ASSET_CDN_URL;",
  "const asset = (path: string) => {",
  `  if (import.meta.env.DEV) return ${BT}/assets/Images/\${path}${BT};`,
  `  if (CDN) return ${BT}\${CDN.endsWith("/") ? CDN.slice(0, -1) : CDN}/preview/\${path}${BT};`,
  `  return ${BT}/preview/\${path}${BT};`,
  "};",
  "",
  "export const icons: Icon[] = [",
  clientRows,
  "];",
  "",
  "export const categories: string[] = [...new Set(icons.map((icon) => icon.category))];",
  "",
].join("\n");

writeFileSync("src/data/icons.generated.ts", clientManifest);

// Server-side twin: plain data with no import.meta, so the Worker can validate
// ids without pulling Vite's client env into the Workers runtime.
const serverRows = icons
  .map(({ id, name }) => `  ${JSON.stringify(id)}: { name: ${JSON.stringify(name)}, key: ${JSON.stringify(`${id}.png`)} },`)
  .join("\n");

writeFileSync(
  "worker/icons.generated.ts",
  `// Generated by scripts/generate-manifest.mjs — do not edit by hand.
// \`key\` is the R2 object path under preview/ and full/. Slugged, so no key ever
// contains a space or a character that needs URL-encoding.
export const iconsById: Record<string, { name: string; key: string }> = {
${serverRows}
};
`
);

console.log(`${icons.length} icons, ${new Set(icons.map((i) => i.category)).size} categories`);
